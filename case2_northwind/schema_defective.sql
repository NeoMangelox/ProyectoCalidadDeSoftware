-- Dialecto PostgreSQL 16/17 | 14 tablas | 10 instancias de defecto
-- IDs (D<tipo>-<n>) coinciden con defects_manifest.json
-- Adaptacion unica fuera de los defectos: orders.order_id usa IDENTITY
