-- CASO 2 - Northwind-PostgreSQL | schema_ground_truth.sql
-- Referencia: defectos inyectados corregidos + todas las FK + indices de FK.
-- 15 tablas (14 + customer_phones). Los "smells nativos" del Northwind
-- original (ver defects_manifest.json -> known_native_smells) se conservan
-- a proposito: el GT corrige unicamente lo inyectado.
-- =====================================================================

CREATE TABLE region (
    region_id           SMALLINT NOT NULL PRIMARY KEY,
    region_description  VARCHAR(60) NOT NULL
);

CREATE TABLE territories (
    territory_id           VARCHAR(20) NOT NULL PRIMARY KEY,
    territory_description  VARCHAR(60) NOT NULL,
    region_id              SMALLINT NOT NULL REFERENCES region (region_id)
);

CREATE TABLE employees (
    employee_id        SMALLINT NOT NULL PRIMARY KEY,
    last_name          VARCHAR(20) NOT NULL,
    first_name         VARCHAR(10) NOT NULL,
    title              VARCHAR(30),
    title_of_courtesy  VARCHAR(25),
    birth_date         DATE,
    hire_date          DATE,
    address            VARCHAR(60),
    city               VARCHAR(15),
    region             VARCHAR(15),
    postal_code        VARCHAR(10),
    country            VARCHAR(15),
    home_phone         VARCHAR(24),
    extension          VARCHAR(4),
    photo              BYTEA,
    notes              TEXT,
    reports_to         SMALLINT REFERENCES employees (employee_id),
    photo_path         VARCHAR(255)
);

CREATE TABLE employee_territories (
    employee_id   SMALLINT NOT NULL REFERENCES employees (employee_id),
    territory_id  VARCHAR(20) NOT NULL REFERENCES territories (territory_id),
    PRIMARY KEY (employee_id, territory_id)
);

CREATE TABLE categories (
    category_id    SMALLINT NOT NULL PRIMARY KEY,
    category_name  VARCHAR(15) NOT NULL,
    description    TEXT,
    picture        BYTEA
);

CREATE TABLE suppliers (
    supplier_id    SMALLINT NOT NULL PRIMARY KEY,
    company_name   VARCHAR(40) NOT NULL,
    contact_name   VARCHAR(30),
    contact_title  VARCHAR(30),
    address        VARCHAR(60),
    city           VARCHAR(15),
    region         VARCHAR(15),
    postal_code    VARCHAR(10),
    country        VARCHAR(15),
    phone          VARCHAR(24),
    fax            VARCHAR(24),
    homepage       TEXT
);

CREATE TABLE shippers (
    shipper_id    SMALLINT NOT NULL PRIMARY KEY,
    company_name  VARCHAR(40) NOT NULL,
    phone         VARCHAR(24)
);

CREATE TABLE customer_demographics (
    customer_type_id  VARCHAR(5) NOT NULL PRIMARY KEY,
    customer_desc     TEXT
);

CREATE TABLE us_states (
    state_id      SMALLINT NOT NULL PRIMARY KEY,
    state_name    VARCHAR(100),
    state_abbr    VARCHAR(2),
    state_region  VARCHAR(50)
);

CREATE TABLE customers (
    customer_id    VARCHAR(5) NOT NULL PRIMARY KEY,
    company_name   VARCHAR(40) NOT NULL,
    contact_name   VARCHAR(30),
    contact_title  VARCHAR(30),
    address        VARCHAR(60),
    city           VARCHAR(15),
    region         VARCHAR(15),
    postal_code    VARCHAR(10),
    country        VARCHAR(15),
    fax            VARCHAR(24)
);

CREATE TABLE customer_phones (                         -- corrige D1-01
    customer_id  VARCHAR(5) NOT NULL REFERENCES customers (customer_id) ON DELETE CASCADE,
    phone        VARCHAR(24) NOT NULL,
    PRIMARY KEY (customer_id, phone)
);

CREATE TABLE customer_customer_demo (
    customer_id       VARCHAR(5) NOT NULL REFERENCES customers (customer_id),
    customer_type_id  VARCHAR(5) NOT NULL REFERENCES customer_demographics (customer_type_id),
    PRIMARY KEY (customer_id, customer_type_id)
);

CREATE TABLE products (
    product_id         SMALLINT NOT NULL PRIMARY KEY,
    product_name       VARCHAR(40) NOT NULL,
    supplier_id        SMALLINT REFERENCES suppliers (supplier_id) ON DELETE RESTRICT,   -- D4-06
    category_id        SMALLINT REFERENCES categories (category_id) ON DELETE RESTRICT,  -- D4-05
    quantity_per_unit  VARCHAR(20),
    unit_price         REAL,
    units_in_stock     SMALLINT,
    units_on_order     SMALLINT,
    reorder_level      SMALLINT,
    discontinued       INTEGER NOT NULL
);

CREATE TABLE orders (
    order_id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       VARCHAR(5) REFERENCES customers (customer_id) ON DELETE RESTRICT,  -- D4-01
    employee_id       SMALLINT REFERENCES employees (employee_id),
    order_date        DATE,
    required_date     DATE,
    shipped_date      DATE,
    ship_via          SMALLINT REFERENCES shippers (shipper_id) ON DELETE RESTRICT,      -- D4-02
    freight           REAL,
    ship_name         VARCHAR(40),
    ship_address      VARCHAR(60),
    ship_city         VARCHAR(15),
    ship_region       VARCHAR(15),
    ship_postal_code  VARCHAR(10),
    ship_country      VARCHAR(15)
);

CREATE TABLE order_details (                           -- D2-01/D2-02 eliminados
    order_id    SMALLINT NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,       -- D4-03
    product_id  SMALLINT NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,  -- D4-04
    unit_price  REAL NOT NULL,
    quantity    SMALLINT NOT NULL CHECK (quantity > 0),
    discount    REAL NOT NULL CHECK (discount >= 0 AND discount <= 1),
    PRIMARY KEY (order_id, product_id)
);

-- Indices sobre FK (PostgreSQL no los crea automaticamente)
CREATE INDEX idx_orders_customer       ON orders (customer_id);
CREATE INDEX idx_orders_employee       ON orders (employee_id);
CREATE INDEX idx_orders_ship_via       ON orders (ship_via);
CREATE INDEX idx_order_details_product ON order_details (product_id);
CREATE INDEX idx_products_category     ON products (category_id);
CREATE INDEX idx_products_supplier     ON products (supplier_id);
CREATE INDEX idx_territories_region    ON territories (region_id);
